using System.Text.Encodings.Web;
using System.Text.Unicode;
using MealPlanner.Application;
using MealPlanner.Infrastructure;
using MealPlanner.Web.Components;
using MealPlanner.Web.Endpoints;
using MealPlanner.Web.Extensions;
using Scalar.AspNetCore;

WebApplicationBuilder builder = WebApplication.CreateBuilder(args);

builder.Services.AddRazorComponents()
    .AddInteractiveServerComponents();

builder.Services.AddCascadingAuthenticationState();

builder.Services.ConfigureHttpJsonOptions(options =>
    options.SerializerOptions.Encoder = JavaScriptEncoder.Create(
        UnicodeRanges.BasicLatin,
        UnicodeRanges.Cyrillic));

// Registers services of the Application layer
builder.Services.AddApplication(builder.Configuration);

// Registers services of the Infrastructure layer
builder.Services.AddInfrastructure(builder.Configuration);

// Cookie-based authentication, roles, and authorization policies.
builder.Services.AddApplicationAuthentication();

// Endpoints are discovered by scanning the assembly - see EndpointExtensions.
builder.Services.AddEndpoints();

// The OpenAPI description is generated from route metadata
builder.Services.AddOpenApi(options =>
{
    options.AddDocumentTransformer<OpenApiDocumentInfo>();
    options.AddSchemaTransformer<OpenApiEnumValues>();
});

builder.Services.AddHealthChecks();

// Error responses should have a consistent structure even
// when they are generated by ASP.NET Core itself, for
// example because of an invalid request body, an invalid
// route parameter type, or an unhandled exception.
builder.Services.AddProblemDetails();

WebApplication app = builder.Build();

if (app.Environment.IsDevelopment())
{
    // Applies migrations and fills the catalog with data
    await app.PrepareDatabaseAsync();
}

await app.WarmUpCatalogAsync();

if (app.Environment.IsDevelopment())
{
    app.MapOpenApi();
    app.MapScalarApiReference(options => options
        .WithTitle("Meal Planner API")
        .WithTheme(ScalarTheme.BluePlanet));
}
else
{
    app.UseExceptionHandler("/Error", createScopeForErrors: true);
    app.UseHsts();
}

app.UseWhen(
    context => !context.Request.Path.StartsWithSegments("/api"),
    branch => branch.UseStatusCodePagesWithReExecute(
        "/not-found",
        createScopeForStatusCodePages: true));

bool runningInContainer = app.Configuration.GetValue<bool>("DOTNET_RUNNING_IN_CONTAINER");

if (!runningInContainer)
{
    app.UseHttpsRedirection();
}

app.UseAuthentication();
app.UseAuthorization();

app.UseAntiforgery();

app.MapStaticAssets();

app.MapHealthChecks("/health");

app.MapEndpoints(app.MapGroup("api").RequireAuthorization());

app.MapRazorComponents<App>()
    .AddInteractiveServerRenderMode();

app.Run();

public partial class Program;
