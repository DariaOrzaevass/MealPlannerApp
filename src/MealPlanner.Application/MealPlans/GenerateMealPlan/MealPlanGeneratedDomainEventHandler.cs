using System;
using System.Collections.Generic;
using System.Text;
using MealPlanner.Application.Abstractions.Messaging;
using MealPlanner.Domain.MealPlans.Events;
using Microsoft.Extensions.Logging;

namespace MealPlanner.Application.MealPlans.GenerateMealPlan;

// Logs generation of the meal plan. Handler does not notify or change anything.
// Its main purpose is to collect in one place data for the clear results of solver performances.
internal sealed class MealPlanGeneratedDomainEventHandler(
    ILogger<MealPlanGeneratedDomainEventHandler> logger)
    : IDomainEventHandler<MealPlanGeneratedDomainEvent>
{
    public Task Handle(
        MealPlanGeneratedDomainEvent domainEvent,
        CancellationToken cancellationToken)
    {
        logger.LogInformation(
            "Meal plan {PlanId} was generated by {Algorithm} in {Elapsed} ms.",
            domainEvent.MealPlanId.Value,
            domainEvent.Algorithm,
            domainEvent.GenerationMs);

        return Task.CompletedTask;
    }
}
